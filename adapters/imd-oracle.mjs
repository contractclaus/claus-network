import { randomBytes, randomUUID } from 'node:crypto';
import { amount, canonical, contentHash, copy, digest, integer, requireThat, text } from '../src/shared/index.mjs';
import {validateOraclePrepared}from'../src/deals/decision.mjs';

export const IMD_ORACLE = Object.freeze({ origin: 'https://api.imd.fun', network: 'eip155:1',
  asset: '0xd34a99bc0f67ae1bbd63c660e6d0b0dd03e263b7',
  payTo: '0x4e0fa57bde726079356537e2f34d671e9f41adbc', maximum: '500000000000000000',
  policyVersion: 'oracle-1' });
const hash = value => digest(value).slice(7);
const id = value => { requireThat(typeof value === 'string' && /^[A-Za-z0-9][A-Za-z0-9_-]{0,127}$/.test(value), 'invalid_provider_id'); return value; };
// Exact fixed question is generated by the agreement worker, never a caller URL.
export function oracleRequest(input) {
  requireThat(input?.v===1 && input.evidence==='panel' && input.answerType==='uint256' &&
    input.panelSize===5 && input.quorum===4 && input.toleranceBps===0 && input.validForSeconds===86400 &&
    [1,11155111].includes(input.chainId) && input.consumer?.chainId===input.chainId &&
    /^0x[0-9a-f]{40}$/.test(input.consumer?.verifyingContract??'') &&
    typeof input.question==='string' && input.question.startsWith('For Claus agreement case sha256:') && input.question.length<=2000 &&
    Number.isSafeInteger(input.window?.fromBlock)&&Number.isSafeInteger(input.window?.toBlock)&&input.window.fromBlock<=input.window.toBlock,
    'invalid_deal_oracle');
  return {action:'oracle.request',input};
}

export async function boundedResponse(response, maximum = 1048576) {
  requireThat(response.body, 'provider_empty_response');
  const reader = response.body.getReader(), chunks = []; let bytes = 0;
  try {
    for (;;) {
      const { done, value } = await reader.read(); if (done) break;
      bytes += value.byteLength; requireThat(bytes <= maximum, 'provider_response_too_large'); chunks.push(value);
    }
  } catch (error) { await reader.cancel().catch(() => {}); throw error; }
  return new TextDecoder('utf-8', { fatal: true }).decode(Buffer.concat(chunks));
}

export function createImdOracleProvider({ store, sealer, resolveInput, verifyPinned, fetch: fetcher = globalThis.fetch, now = () => Date.now() }) {
  requireThat(typeof verifyPinned==='function','oracle_chain_verifier_required');
  async function call(path, { body, token, method = 'GET', statuses = [200], headers = {}, json = true } = {}) {
    let response;
    try {
      response = await fetcher(IMD_ORACLE.origin + path, { method, redirect: 'error', signal: AbortSignal.timeout(30000),
        headers: { accept: json ? 'application/json' : 'text/markdown', ...(body ? { 'content-type': 'application/json' } : {}),
          ...(token ? { authorization: 'Bearer ' + token } : {}), ...headers }, ...(body ? { body: JSON.stringify(body) } : {}) });
    } catch { throw Object.assign(Error('provider_outcome_unknown'), { code: 'provider_outcome_unknown' }); }
    if (!statuses.includes(response.status)) {
      await response.body?.cancel().catch(() => {});
      throw Object.assign(Error('provider_request_rejected'), { code: 'provider_request_rejected', httpStatus: response.status });
    }
    const raw = await boundedResponse(response);
    if (!json) return raw;
    requireThat(/^application\/json(?:;|$)/i.test(response.headers.get('content-type') ?? ''), 'provider_invalid_response');
    try { return JSON.parse(raw); } catch { throw Object.assign(Error('provider_invalid_response'), { code: 'provider_invalid_response' }); }
  }
  function validateQuote(quote, request) {
    requireThat(quote?.v === 1 && quote.action === 'oracle.request' && quote.policyVersion === IMD_ORACLE.policyVersion &&
      quote.payment?.scheme === 'exact' && quote.payment.network === IMD_ORACLE.network &&
      quote.payment.asset === IMD_ORACLE.asset && quote.payment.payTo === IMD_ORACLE.payTo && quote.payment.decimals === 18 &&
      quote.terms?.purchase === 'action-admission' && quote.terms.resultGuaranteed === false, 'provider_terms_changed');
    id(quote.id); integer(quote.issuedAt); integer(quote.expiresAt);
    requireThat(amount(quote.payment.amount) > 0n && amount(quote.payment.amount) <= amount(IMD_ORACLE.maximum), 'provider_price_exceeds_profile');
    requireThat(quote.expiresAt > quote.issuedAt && quote.expiresAt - quote.issuedAt <= 600, 'invalid_provider_expiry');
    requireThat(/^[0-9a-f]{64}$/.test(quote.quoteHash) && /^[0-9a-f]{64}$/.test(quote.inputHash), 'provider_input_mismatch');
  }
  async function record(offerId) {
    const mapping = (await store.read('imd-offer-index', id(offerId)))?.value;
    requireThat(mapping, 'provider_quote_missing');
    const value = (await store.read('imd-orders', mapping.id))?.value;
    requireThat(value && value.quote?.id === offerId, 'provider_quote_missing');
    return { ...value, credentials: sealer.open(mapping.id, value.sealed) };
  }
  return {
    id: 'imd-deal-oracle-v1',
    async quote({ projectId, inputHash, quoteId }) {
      text(projectId); contentHash(inputHash); text(quoteId);
      const request = oracleRequest(await resolveInput(projectId, inputHash));
      const key = digest({ projectId, quoteId }), binding = digest({ request, inputHash });
      const intent = await store.transaction(async tx => {
        const old = await tx.read('imd-orders', key);
        if (old) { requireThat(old.value.binding === binding, 'idempotency_conflict'); return old.value; }
        const value = { id: key, projectId, inputHash, binding, request, quote: null, requestKey: randomUUID(),
          sealed: sealer.seal(key, { requestToken: randomBytes(32).toString('hex') }), createdAt: now() };
        await tx.write('imd-orders', key, value, 0); return value;
      });
      let quote = intent.quote,preparedInput=intent.preparedInput;
      if (!quote) {
        const secret = sealer.open(key, intent.sealed);
        const out = await call('/requests/quote', { method: 'POST', token: secret.requestToken,
          body: { ...request, requestKey: intent.requestKey }, statuses: [200, 201] });
        requireThat(out.order?.requestKey === intent.requestKey, 'provider_order_mismatch');
        quote = out.order.quote; validateQuote(quote, request);
        // Keep the original provider ID even when later wrapper validation fails.
        await store.transaction(async tx=>{const old=await tx.read('imd-orders',key);if(old.value.quote){requireThat(canonical(old.value.quote)===canonical(quote),'provider_order_changed');return;}await tx.write('imd-orders',key,{...old.value,quote},old.revision);});
      }
      requireThat(quote.issuedAt<=Math.floor(now()/1000)+5,'provider_clock_ahead');
      requireThat(quote.expiresAt*1000>now()+60000,'oracle_quote_expired');
      if(!preparedInput){
        const secret=sealer.open(key,intent.sealed),challenge=await call('/requests/'+id(quote.id)+'/submit',{method:'POST',token:secret.requestToken,statuses:[402]});
        requireThat(canonical(challenge.quote)===canonical(quote),'provider_order_changed');preparedInput=validateOraclePrepared(challenge.input,request.input);
        requireThat(quote.inputHash===hash(preparedInput),'provider_input_mismatch');await verifyPinned(request.input,preparedInput.pinned);
        await store.transaction(async tx => {
          const old = await tx.read('imd-orders', key);
          if(old.value.preparedInput){requireThat(canonical(old.value.quote)===canonical(quote)&&canonical(old.value.preparedInput)===canonical(preparedInput),'provider_order_changed');return;}
          if(old.value.quote)requireThat(canonical(old.value.quote)===canonical(quote),'provider_order_changed');
          await tx.write('imd-orders', key, { ...old.value, quote,preparedInput }, old.revision);
          const index=await tx.read('imd-offer-index',quote.id);if(index)requireThat(index.value.id===key,'provider_order_changed');else await tx.write('imd-offer-index', quote.id, { id: key }, 0);
        });
      }
      return { id: quote.id, provider: 'imd-deal-oracle-v1', inputHash, asset: 'eip155:1/erc20:' + IMD_ORACLE.asset,
        maximum: quote.payment.amount, expiresAt: quote.expiresAt * 1000,preparedInput,providerInputHash:quote.inputHash };
    },
    async challenge(offerId) {
      const saved = await record(offerId);
      const result = await call('/requests/' + id(offerId) + '/submit', { method: 'POST', token: saved.credentials.requestToken, statuses: [402] });
      validateQuote(result.quote, saved.request);
      validateOraclePrepared(result.input,saved.request.input);requireThat(canonical(result.quote)===canonical(saved.quote)&&canonical(result.input)===canonical(saved.preparedInput)&&result.quote.inputHash===hash(result.input),'provider_challenge_mismatch');await verifyPinned(saved.request.input,result.input.pinned);
      requireThat(result.x402Version === 2 && result.resourceUrl === IMD_ORACLE.origin + '/requests/' + offerId &&
        result.resource?.url === result.resourceUrl && /^[0-9a-f]{64}$/.test(result.requesterScopeHash) &&
        Array.isArray(result.accepts) && result.accepts.length === 1, 'provider_challenge_mismatch');
      const accepted = result.accepts[0];
      requireThat(accepted.scheme === 'exact' && accepted.network === IMD_ORACLE.network && accepted.asset === IMD_ORACLE.asset &&
        accepted.payTo === IMD_ORACLE.payTo && accepted.amount === saved.quote.payment.amount &&
        accepted.extra?.assetTransferMethod === 'permit2' && Number.isSafeInteger(accepted.maxTimeoutSeconds) &&
        accepted.maxTimeoutSeconds > 0 && accepted.maxTimeoutSeconds <= 300, 'provider_terms_changed');
      return result;
    },
    // Payment material comes only from the separate bounded signer; callers
    // must persist an effect intent before this network write.
    async submit(offerId, material) {
      const saved = await record(offerId);
      requireThat(typeof material.paymentSignature === 'string' && material.paymentSignature.length < 32768 &&
        /^0x[0-9a-f]{130}$/i.test(material.quoteSignature), 'invalid_payment_material');
      return call('/requests/' + id(offerId) + '/submit', { method: 'POST', token: saved.credentials.requestToken,
        headers: { 'PAYMENT-SIGNATURE': material.paymentSignature }, body: { quoteSignature: material.quoteSignature }, statuses: [200, 202] });
    },
    async status(offerId) {
      const saved = await record(offerId);
      const out = await call('/requests/' + id(offerId), { token: saved.credentials.requestToken });
      requireThat(out.order?.id === offerId && ['quoted', 'expired', 'payment_pending', 'payment_failed', 'paid', 'admission_pending', 'admitted'].includes(out.status), 'provider_invalid_status');
      if (out.order.quote) requireThat(canonical(out.order.quote) === canonical(saved.quote), 'provider_order_changed');
      return out;
    },
    async oracle(requestId) {
      const request=await call('/oracle/requests/'+id(requestId));
      requireThat(request.id===requestId&&typeof request.status==='string','provider_invalid_oracle');
      if(request.status!=='attested')return {complete:false,state:request.status};
      const attestation=await call('/oracle/requests/'+id(requestId)+'/attestation');
      return {complete:true,state:request.status,request,attestation};
    }
  };
}
